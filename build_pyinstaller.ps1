#Requires -Version 5.1
<#
.SYNOPSIS
    Build ED:Event2Led using PyInstaller (Option A: single-folder exe).

.DESCRIPTION
    1. Runs PyInstaller with EDEvent2Led.spec
    2. Copies default config files to dist/EDEvent2Led/config/
    3. Creates a sanitized settings.json (no personal paths)
    4. Creates README.txt with instructions
    5. Optionally creates a ZIP archive

.USAGE
    .\build_pyinstaller.ps1
    .\build_pyinstaller.ps1 -Version "1.2.4"
    .\build_pyinstaller.ps1 -Zip

.PARAMETER Version
    Version string for the build (default: from git or "dev")

.PARAMETER Zip
    If specified, creates a ZIP archive of the output folder

.PARAMETER Clean
    If specified, cleans the dist/ folder before building
#>

param(
    [string]$Version = "",
    [switch]$Zip,
    [switch]$Clean
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$ProjectRoot = $PSScriptRoot
$BuildDir    = Join-Path $ProjectRoot "build"
$DistDir     = Join-Path $ProjectRoot "dist"

# ── Helpers ───────────────────────────────────────────────────────────────────

function Write-Step([string]$msg) {
    Write-Host "`n[..] $msg" -ForegroundColor Cyan
}
function Write-Ok([string]$msg) {
    Write-Host "[OK] $msg" -ForegroundColor Green
}
function Write-Warn([string]$msg) {
    Write-Host "[WARN] $msg" -ForegroundColor Yellow
}
function Write-Err([string]$msg) {
    Write-Host "[ERROR] $msg" -ForegroundColor Red
}

# ── Version detection ─────────────────────────────────────────────────────────

if (-not $Version) {
    $Version = (git describe --tags --always 2>$null) -replace '^v', ''
    if (-not $Version) { $Version = "dev" }
}

# ── Bake version into _version.py ────────────────────────────────────────────
# The frozen app cannot call git (not in the user's install).
# _version.py is imported by settings_api._get_git_info() when sys.frozen=True.
# This file is generated at build time and must NOT be committed (see .gitignore).

$buildDate = Get-Date -Format "yyyy.MM.dd"
$versionPySrc = "$ProjectRoot\src\_version.py"
@"
# Auto-generated by build_pyinstaller.ps1 at build time — do not edit or commit.
VERSION    = '$Version'
BUILD_DATE = '$buildDate'
"@ | Set-Content $versionPySrc -Encoding UTF8
Write-Ok "Version baked: v$Version  ($buildDate) -> src\_version.py"

# ── Python/PyInstaller check ──────────────────────────────────────────────────

Write-Step "Checking Python..."
$pyCmd = python --version 2>$null
if (-not $pyCmd) {
    $pyCmd = py --version 2>$null
}
if (-not $pyCmd) {
    Write-Err "Python not found. Please install Python 3.11+"
    exit 1
}
Write-Ok "Found: $pyCmd"

Write-Step "Checking PyInstaller..."
$pyinstVersion = pyinstaller --version 2>$null
if (-not $pyinstVersion) {
    Write-Warn "PyInstaller not found. Installing..."
    pip install pyinstaller
}
$pyinstVersion = pyinstaller --version 2>$null
Write-Ok "PyInstaller: $pyinstVersion"

# ── Clean dist ───────────────────────────────────────────────────────────────

if ($Clean) {
    Write-Step "Cleaning dist/..."
    if (Test-Path $DistDir) {
        Remove-Item $DistDir -Recurse -Force
    }
    Write-Ok "Cleaned"
}

# ── Run PyInstaller ──────────────────────────────────────────────────────────

Write-Step "Running PyInstaller..."
Write-Host "This may take 2-5 minutes..." -ForegroundColor DarkGray

Push-Location $ProjectRoot
try {
    pyinstaller build\EDEvent2Led.spec --noconfirm
    if ($LASTEXITCODE -ne 0) {
        Write-Err "PyInstaller failed with exit code $LASTEXITCODE"
        exit 1
    }
}
finally {
    Pop-Location
}
Write-Ok "PyInstaller completed"

# Clean up the baked _version.py from source tree (it's a build artifact)
if (Test-Path $versionPySrc) {
    Remove-Item $versionPySrc -Force
    Write-Ok "Cleaned: src\_version.py (build artifact removed)"
}

# ── Output path ──────────────────────────────────────────────────────────────

$OutDir = Join-Path $DistDir "EDEvent2Led"

if (-not (Test-Path $OutDir)) {
    Write-Err "Output directory not found: $OutDir"
    exit 1
}

# ── Copy and sanitize config ──────────────────────────────────────────────────

Write-Step "Preparing config/..."

$ConfigSource = Join-Path $ProjectRoot "config"
$ConfigDest   = Join-Path $OutDir "config"

if (Test-Path $ConfigDest) {
    Remove-Item $ConfigDest -Recurse -Force
}
New-Item $ConfigDest -ItemType Directory | Out-Null

# Copy all config files except settings (will be created fresh)
$configFiles = @(
    "visual_effects.json",
    "event_mappings.json",
    "color_schemes.json",
    "keyboard_presets.json",
    "event_catalog.json"
)
foreach ($f in $configFiles) {
    $src = Join-Path $ConfigSource $f
    if (Test-Path $src) {
        Copy-Item $src $ConfigDest -Force
        Write-Ok "Copied: $f"
    }
}

# Sanitize keyboard_presets.json (remove user's LED colors)
$presetsPath = Join-Path $ConfigDest "keyboard_presets.json"
if (Test-Path $presetsPath) {
    $p = Get-Content $presetsPath | ConvertFrom-Json
    foreach ($presetId in @("1","2","3")) {
        if ($p.presets.$presetId) {
            $p.presets.$presetId.led_colors = @{}
        }
    }
    $p.active_preset = "1"
    $p.lock_keyboard  = $false
    $p | ConvertTo-Json -Depth 10 | Set-Content $presetsPath
    Write-Ok "Sanitized: keyboard_presets.json (led_colors cleared)"
}

# Create clean settings.json
$settingsPath = Join-Path $ConfigDest "settings.json"
@{
    openrgb_host     = "localhost"
    openrgb_port     = 6742
    language         = "en"
    theme            = "elite"
    show_welcome    = $true
    completed_guides = @{}
} | ConvertTo-Json | Set-Content $settingsPath
Write-Ok "Created: settings.json (sanitized)"

# Create empty mappings
@{
    version   = 2
    mappings  = @{}
} | ConvertTo-Json | Set-Content (Join-Path $ConfigDest "event_mappings.json")

# ── Create README.txt ────────────────────────────────────────────────────────

Write-Step "Creating README.txt..."
$readme = @"
ED:Event2Led v$Version — Guida rapida
====================================

PREREQUISITI
------------
1. Windows 10/11 x64
2. OpenRGB installato e in esecuzione
   - Apri OpenRGB > Settings > Enable SDK Server > Start
   - (default: porta 6742)
3. Elite Dangerous installato (per monitoraggio live)

AVVIO
------
Doppio click su EDEvent2Led.exe
L'app apre il browser su http://localhost:8000

AGGIORNAMENTO DA UNA VERSIONE PRECEDENTE
----------------------------------------
1. Chiudi l'app. OpenRGB deve restare acceso.
2. Scarica la nuova versione in una cartella nuova.
3. Copia la cartella config\ della vecchia versione dentro
   quella nuova (sovrascrivendo i file).
4. Avvia EDEvent2Led.exe: i file di configurazione dei
   dispositivi vengono aggiornati automaticamente al primo
   avvio. Le copie dei file originali si chiamano
   *.v1.bak.json e restano in config\.
Se qualcosa non torna, ripristina un file rinominando la sua
copia (es. device_config.v1.bak.json -> device_config.json).

NOTE
----
- Se la porta 8000 e' occupata: modifica config\settings.json
  aggiungendo  "web_port": 8081  (o altra porta libera)
- I tuoi effetti e mappature vengono salvati in config\
- Per segnalare un bug: includi il contenuto della console

LICENZA
-------
PolyForm Noncommercial 1.0.0 (source-available): uso, modifica e
condivisione consentiti per qualsiasi scopo non commerciale (anche
stream e video del gameplay, pure su canali monetizzati).
L'uso commerciale non e' consentito. Build ufficiali solo su:
https://github.com/leandor70/EDEvent2Led/releases
Testo completo in LICENSE; vedi anche NOTICE.md e THIRD-PARTY.md.

VERSIONE: $Version
DATA BUILD: $(Get-Date -Format "yyyy-MM-dd")
"@
$readme | Set-Content (Join-Path $OutDir "README.txt") -Encoding UTF8
Write-Ok "Created: README.txt"

# Include the license text in the package
$licenseSrc = Join-Path $ProjectRoot "LICENSE"
if (Test-Path $licenseSrc) {
    Copy-Item $licenseSrc (Join-Path $OutDir "LICENSE") -Force
    Write-Ok "Copied: LICENSE"
} else {
    Write-Warn "LICENSE not found in project root - package built without it"
}
foreach ($doc in "NOTICE.md", "THIRD-PARTY.md") {
    $docSrc = Join-Path $ProjectRoot $doc
    if (Test-Path $docSrc) {
        Copy-Item $docSrc (Join-Path $OutDir $doc) -Force
        Write-Ok "Copied: $doc"
    }
}
$licDir = Join-Path $ProjectRoot "licenses"
if (Test-Path $licDir) {
    Copy-Item $licDir (Join-Path $OutDir "licenses") -Recurse -Force
    Write-Ok "Copied: licenses\"
}

# ── Create ZIP ───────────────────────────────────────────────────────────────

if ($Zip) {
    Write-Step "Creating ZIP archive..."
    $ZipName = "ED-Event2Led-v$Version-win64-PyInstaller"
    $ZipPath = Join-Path $DistDir "$ZipName.zip"

    Compress-Archive -Path $OutDir -DestinationPath $ZipPath -Force
    $sizeMB = [math]::Round((Get-Item $ZipPath).Length / 1MB, 1)
    Write-Ok "Created: dist\$ZipName.zip ($sizeMB MB)"
}

# ── Summary ──────────────────────────────────────────────────────────────────

$sizeMB = [math]::Round((Get-ChildItem $OutDir -Recurse | Measure-Object -Property Length -Sum).Sum / 1MB, 1)

Write-Host "`n============================================================" -ForegroundColor White
Write-Host "  Build completata: ED:Event2Led v$Version" -ForegroundColor Green
Write-Host "  Output: dist\EDEvent2Led\ ($sizeMB MB)" -ForegroundColor Green
Write-Host "  Esegui: dist\EDEvent2Led\EDEvent2Led.exe" -ForegroundColor White
if ($Zip) {
    Write-Host "  ZIP: dist\$ZipName.zip" -ForegroundColor White
}
Write-Host "============================================================`n" -ForegroundColor White
